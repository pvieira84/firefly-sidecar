import_webextension_polyfill.default.runtime.onMessage.addListener((message, sender) => {
  const internal = !sender.tab && sender.id === import_webextension_polyfill.default.runtime.id;
  const amazon = Boolean(sender.tab) && amazonSpainUrl(sender.url || sender.tab.url);
  if (message.action === "collectorReady" && amazon) return collectorReady(sender, message.page);
  const collect = message.action === "sidecarOrders" && amazon;
  if (message.action === "updateProgress" && amazon) return status(message.data?.message || "Collecting orders\u2026").then(() => ({ success: true }));
  if (!internal && !collect) return;
  return (async () => {
    if (collect) {
      const { job } = await import_webextension_polyfill.default.storage.local.get("job");
      if (job?.tabId !== sender.tab.id) throw Error("No active sync for this tab.");
      const s = await settings();
      if (s.url !== job.url || s.account !== job.account) throw Error("Connection changed during collection. Restore the connection before retrying.");
      await import_webextension_polyfill.default.storage.local.set({ pending: { url: s.url, account: s.account, orders: message.orders } });
      await sendPending();
    } else if (message.action === "sync") await begin(message.start, message.end);
    else if (message.action === "retry") await sendPending();
    else if (message.action === "configure") {
      await import_webextension_polyfill.default.alarms.clear("amazon-daily");
      const s = await settings();
      if (s.daily) await import_webextension_polyfill.default.alarms.create("amazon-daily", { periodInMinutes: 1440 });
    } else if (message.action === "stop") {
      const { job } = await import_webextension_polyfill.default.storage.local.get("job");
      if (job) {
        try {
          await import_webextension_polyfill.default.tabs.sendMessage(job.tabId, { action: "stopExport" });
        } catch {
        }
        await import_webextension_polyfill.default.storage.local.remove("job");
      }
      await status("Sync stopped.");
    }
    return { success: true };
  })().catch(async (e) => {
    await status(e.message);
    return { success: false, error: e.message };
  });
});
