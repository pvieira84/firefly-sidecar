const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const elements=new Map();
const get=id=>{if(!elements.has(id))elements.set(id,{value:'',innerHTML:'',textContent:'',addEventListener(){}});return elements.get(id)};
const context=vm.createContext({document:{getElementById:get,querySelectorAll:()=>[]},fetch:()=>new Promise(()=>{}),Intl,URL,URLSearchParams});
vm.runInContext(fs.readFileSync('sidecar/static/app.js','utf8'),context);
vm.runInContext("config={primary_currency:{code:'EUR'},firefly_public_url:'https://firefly.test'}",context);
context.foreign={amount:'2012.41',currency_code:'USD',type:'transfer',foreign_amount:'1785.00',foreign_currency_code:'EUR',pc_amount:'1803.12'};
const run=code=>vm.runInContext(code,context);
assert.equal(run("nativeAmount(foreign,'USD').amount"),'1785.00');
assert.match(run("amountText(foreign.amount,'USD','transfer',foreign)"),/2,012.41.*\(.*1,785.00\)/);
assert(run("amountHtml(foreign.amount,'USD','transfer',foreign)").includes('native-amount'));
assert.equal(run("nativeAmount(foreign,'EUR')"),null);
assert.equal(run("nativeAmount({native_amount:'-1803.12'},'USD').amount"),'1803.12');
assert.equal(run("nativeAmount({pc_amount:'0'},'USD').amount"),'0');
assert.equal(run("nativeAmount({foreign_amount:'1785',foreign_currency_code:'GBP'},'USD')"),null);
assert.equal(run("nativeAmount({pc_amount:null},'USD')"),null);
assert.equal(run("nativeTotal([foreign,foreign],'USD').pc_amount"),'3570.000000000000');
assert.equal(run("Object.keys(nativeTotal([foreign,{}],'USD')).length"),0);
assert.equal(run("nativeAmount({pc_amount:'999',primary_currency_code:'GBP'},'USD')"),null);
context.row={group_id:'1',journal_count:1,title:'Transfer',date:'2026-11-05',type:'transfer',currency:'USD',total:'2012.41',splits:[{...context.foreign,journal_id:'2',description:'CTT',source:'MiniPay',destination:'IGCP'}]};
assert.match(run("duplicateCard(row)"),/native-amount/);
context.event={before:{attributes:{transactions:[context.foreign]}}};
assert.match(run("activityAmounts(event)"),/native-amount/);
console.log('Primary amounts, recorded transfer amount priority, signs, zero, missing data, exact totals, cards and activity passed.');
